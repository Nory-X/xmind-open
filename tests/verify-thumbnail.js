'use strict';

/**
 * Cross-checks the hand-rolled ZIP reader against a REAL .xmind archive.
 *
 * Why this exists: the ZIP reader is the one place where a silent offset bug
 * would be invisible to a stubbed test — the stub would cheerfully hand back
 * whatever the test pretends is inside. So the reader also gets exercised on
 * an actual XMind file, against an independent implementation (Python's
 * `zipfile`), comparing sizes and SHA-256 digests.
 *
 * Usage:
 *   node verify-thumbnail.js <path/to/file.xmind>
 *   XMO_SAMPLE=/path/to/file.xmind node verify-thumbnail.js
 * A real file is required — there is deliberately no bundled sample, so the
 * check can never pass against a fixture that was generated by the same code.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const Module = require('module');

const SAMPLE = process.env.XMO_SAMPLE || '';
const MAIN = path.join(__dirname, '..', 'main.js');
const PNG_MAGIC = '89504e470d0a1a0a';

/** main.js destructures a handful of obsidian exports at load time, so the
 *  module needs a minimal stub even for pure functions. */
function loadTestHooks() {
  const origLoad = Module._load;
  Module._load = function (request) {
    if (request === 'obsidian') {
      return {
        Plugin: class {},
        PluginSettingTab: class {},
        Setting: class {},
        FileView: class {},
        Notice: class {},
        TFile: class {},
        setIcon() {},
      };
    }
    return origLoad.apply(this, arguments);
  };
  try {
    return require(MAIN).__test;
  } finally {
    Module._load = origLoad;
  }
}

function main() {
  const target = process.argv[2] || SAMPLE;
  if (!target) {
    console.error('用法: node verify-thumbnail.js <path/to/file.xmind>');
    process.exit(2);
  }
  if (!fs.existsSync(target)) {
    console.error('找不到文件: ' + target);
    process.exit(2);
  }

  const { readZipEntry, THUMBNAIL_ENTRY, toDataUri } = loadTestHooks();
  const nodeBuf = fs.readFileSync(target);
  // Obsidian's vault.readBinary() hands the plugin an ArrayBuffer — mirror
  // exactly that, rather than passing a Node Buffer with a non-zero offset.
  const arrayBuffer = nodeBuf.buffer.slice(
    nodeBuf.byteOffset,
    nodeBuf.byteOffset + nodeBuf.byteLength
  );

  const png = readZipEntry(arrayBuffer, THUMBNAIL_ENTRY);
  if (!png) {
    console.log('未找到 ' + THUMBNAIL_ENTRY + '（该档案没有预览图，属正常降级路径）');
    process.exit(1);
  }

  const magic = Buffer.from(png.slice(0, 8)).toString('hex');
  const digest = crypto.createHash('sha256').update(png).digest('hex');
  const uri = toDataUri(png, 'image/png');

  console.log('文件        : ' + path.basename(target));
  console.log('档案字节数  : ' + nodeBuf.byteLength);
  console.log('条目        : ' + THUMBNAIL_ENTRY);
  console.log('解出字节数  : ' + png.byteLength);
  console.log('PNG 魔数    : ' + (magic === PNG_MAGIC ? 'OK' : '异常') + ' (' + magic + ')');
  console.log('sha256      : ' + digest);
  console.log('data URI    : ' + uri.slice(0, 44) + '...  (共 ' + uri.length + ' 字符)');

  console.log('\n--- 用下面的命令核对 digest ---');
  console.log(
    'python -c "import zipfile,hashlib,sys;' +
      "d=zipfile.ZipFile(sys.argv[1]).read('" +
      THUMBNAIL_ENTRY +
      "');print(len(d),hashlib.sha256(d).hexdigest())\" \"" +
      target +
      '"'
  );
}

main();
